# --------------------------------------------------------------------------- REST client


class _Api:
    """A scripted local HTTP server standing in for api.github.com."""

    def __init__(self) -> None:
        self.requests: list[dict[str, Any]] = []
        self.responses: dict[tuple[str, str], tuple[int, dict[str, str], Any]] = {}

    def handler(self) -> type[BaseHTTPRequestHandler]:
        api = self

        class H(BaseHTTPRequestHandler):
            def log_message(self, format: str, *args: Any) -> None:
                pass

            def _serve(self) -> None:
                length = int(self.headers.get("Content-Length") or 0)
                body = json.loads(self.rfile.read(length)) if length else None
                api.requests.append({"method": self.command, "path": self.path, "body": body,
                                     "auth": self.headers.get("Authorization")})  # fmt: skip
                status, headers, payload = api.responses.get(
                    (self.command, self.path), (404, {}, {"message": "Not Found"})
                )
                data = json.dumps(payload).encode()
                self.send_response(status)
                for k, v in headers.items():
                    self.send_header(k, v)
                self.send_header("Content-Length", str(len(data)))
                self.end_headers()
                self.wfile.write(data)

            do_GET = do_POST = _serve

        return H


@pytest.fixture
def api() -> Iterator[tuple[_Api, str]]:
    state = _Api()
    server = ThreadingHTTPServer(("127.0.0.1", 0), state.handler())
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    try:
        yield state, f"http://127.0.0.1:{server.server_address[1]}"
    finally:
        server.shutdown()
        server.server_close()


TOKEN = "ghp_" + "x" * 36


def test_draft_is_hard_coded_and_token_only_in_header(api: tuple[_Api, str]) -> None:
    state, url = api
    state.responses[("POST", "/repos/o/r/pulls")] = (201, {}, {"number": 5, "draft": True})
    gh = RestGitHub(TOKEN, api=url, min_write_interval_s=0)
    pr = gh.create_draft_pull("o/r", title="t", body="b", head="me:ai-patch/x", base="main")
    sent = state.requests[0]
    assert sent["body"]["draft"] is True
    assert sent["auth"] == f"Bearer {TOKEN}"
    assert TOKEN not in json.dumps(sent["body"])
    assert pr["number"] == 5


def test_low_remaining_rate_limit_stops(api: tuple[_Api, str]) -> None:
    state, url = api
    state.responses[("GET", "/repos/o/r")] = (200, {"X-RateLimit-Remaining": "3"}, {"x": 1})
    with pytest.raises(GitHubRateLimited, match="only 3"):
        RestGitHub(TOKEN, api=url).get_repo("o/r")


def test_secondary_limit_aborts_without_retry(api: tuple[_Api, str]) -> None:
    state, url = api
    msg = {"message": "You have exceeded a secondary rate limit"}
    state.responses[("POST", "/repos/o/r/forks")] = (403, {"Retry-After": "60"}, msg)
    with pytest.raises(GitHubRateLimited):
        RestGitHub(TOKEN, api=url, min_write_interval_s=0).create_fork("o/r")
    assert len(state.requests) == 1  # exactly one attempt


def test_errors_redact_tokens(api: tuple[_Api, str]) -> None:
    state, url = api
    state.responses[("GET", "/repos/o/r")] = (500, {}, {"message": f"boom {TOKEN}"})
    with pytest.raises(GitHubError) as ei:
        RestGitHub(TOKEN, api=url).get_repo("o/r")
    assert TOKEN not in str(ei.value)


def test_writes_require_token_and_are_spaced(api: tuple[_Api, str]) -> None:
    state, url = api
    with pytest.raises(GitHubError, match="GITHUB_TOKEN"):
        RestGitHub(None, api=url).create_blob("o/r", "x")
    assert state.requests == []  # refused before any request

    state.responses[("POST", "/repos/o/r/git/blobs")] = (201, {}, {"sha": "s"})
    t = [100.0]
    sleeps: list[float] = []
    gh = RestGitHub(TOKEN, api=url, min_write_interval_s=2.0, clock=lambda: t[0],
                    sleep=sleeps.append)  # fmt: skip
    gh.create_blob("o/r", "a")
    t[0] += 0.5
    gh.create_blob("o/r", "b")
    assert sleeps == [1.5]
    assert gh.write_calls == 2


def test_missing_file_is_none(api: tuple[_Api, str]) -> None:
    _, url = api
    assert RestGitHub(None, api=url).get_file("o/r", "CONTRIBUTING.md") is None


