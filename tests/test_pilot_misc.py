NOW = datetime(2026, 10, 30, tzinfo=UTC)


def _rec(days_ago: float) -> PublishRecord:
    return PublishRecord(
        package_id="p", package_sha256="s", repo_slug="o/r", issue_number=1, pr_number=9,
        pr_url="u", head_branch="ai-patch/x", reviewer="me",
        published_at=(NOW - timedelta(days=days_ago)).isoformat(),
    )  # fmt: skip


def _cls(rec: PublishRecord, pr: dict[str, Any], comments: list[dict[str, Any]] | None = None,
         reviews: list[dict[str, Any]] | None = None) -> dict[str, Any]:  # fmt: skip
    return classify(rec, pr, reviews or [], [], comments or [], own_login="me", now=NOW,
                    ignored_after_days=14)  # fmt: skip


def test_outcome_classification() -> None:
    later = (NOW - timedelta(days=1)).isoformat()
    assert _cls(_rec(5), {"merged_at": later, "state": "closed"})["outcome"] == "merged"
    assert _cls(_rec(5), {"closed_at": later, "state": "closed"})["outcome"] == "closed"
    assert _cls(_rec(20), {"state": "open"})["outcome"] == "ignored"
    assert _cls(_rec(3), {"state": "open"})["outcome"] == "open-waiting"
    reviewer = {"user": {"login": "maintainer", "type": "User"}, "submitted_at": later,
                "state": "CHANGES_REQUESTED"}  # fmt: skip
    row = _cls(_rec(20), {"state": "open"}, reviews=[reviewer])
    assert row["outcome"] == "open-active"
    assert row["review_states"] == "CHANGES_REQUESTED"
    assert row["first_response_hours"] == pytest.approx(19 * 24)


def test_own_and_bot_comments_are_not_human_activity() -> None:
    own = {"user": {"login": "me", "type": "User"}, "created_at": NOW.isoformat()}
    bot = {"user": {"login": "ci", "type": "Bot"}, "created_at": NOW.isoformat()}
    assert _cls(_rec(20), {"state": "open"}, comments=[own, bot])["outcome"] == "ignored"


def test_outcomes_markdown_counts() -> None:
    md = markdown([{"outcome": "merged"}, {"outcome": "ignored"}, {"outcome": "ignored"}])
    assert "| merged | 1 |" in md
    assert "| ignored | 2 |" in md
    assert "| **total** | 3 |" in md


