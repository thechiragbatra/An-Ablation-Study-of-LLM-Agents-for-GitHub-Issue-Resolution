    for cfg_on, flag in [(False, False), (True, False), (False, True)]:
        with pytest.raises(ScanDisabled):
            require_enabled(PilotConfig(code_health_scan=cfg_on), flag)
    require_enabled(PilotConfig(code_health_scan=True), True)


