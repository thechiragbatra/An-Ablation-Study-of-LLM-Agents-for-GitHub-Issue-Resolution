def test_publish_refused_without_approval(gh: FakeGitHub, tmp_path: Path) -> None:
    pkg_dir = write(tmp_path)
    with pytest.raises(PublishRefused, match="approval"):
        _publish(pkg_dir, gh, _allowlisted(tmp_path))
    assert gh.writes == []


def test_approval_is_bound_to_package_contents(gh: FakeGitHub, tmp_path: Path) -> None:
    pkg_dir = write(tmp_path)
    _approve(pkg_dir)
    data = json.loads((pkg_dir / "package.json").read_text())
    data["files"]["calc/stats.py"] += "import os  # sneaked in after approval\n"
    (pkg_dir / "package.json").write_text(json.dumps(data))
    with pytest.raises(PublishRefused, match="changed after approval"):
        _publish(pkg_dir, gh, _allowlisted(tmp_path))
    assert gh.writes == []


def test_approval_requires_typing_the_hash(tmp_path: Path) -> None:
    pkg_dir = write(tmp_path)
