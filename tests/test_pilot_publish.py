def test_publish_via_fork_creates_exactly_one_draft(gh: FakeGitHub, tmp_path: Path) -> None:
    cfg = _allowlisted(tmp_path)
    pkg_dir = write(tmp_path)
    _approve(pkg_dir, reviewer="Chirag")
    result = _publish(pkg_dir, gh, cfg)

    assert gh.write_names == [
        "create_fork", "create_blob", "create_blob", "create_tree", "create_commit",
        "create_ref", "create_draft_pull",
    ]  # fmt: skip
    _, (tree_slug, _, entries) = gh.writes[3]
    assert tree_slug == "me/lib"
    assert {e["path"]: e["mode"] for e in entries} == {
        "calc/stats.py": "100644", "run.sh": "100755",  # executable bit preserved
    }  # fmt: skip
    _, (_, ref, _) = gh.writes[5]
    assert ref == "refs/heads/ai-patch/issue-7-abcd1234"
    pr = gh.drafts[0]
    assert pr["draft"] is True
    assert pr["head"] == "me:ai-patch/issue-7-abcd1234"
    assert pr["base"] == "main"
    assert pr["title"].startswith("[AI-Generated Patch] ")
    assert "Reviewer: Chirag" in pr["body"]
    assert "@@REVIEWER@@" not in pr["body"]
    assert result.pr is not None

    log = load_log(cfg.log_path)
    assert [(r.pr_number, r.reviewer) for r in log] == [(100, "Chirag")]
    assert (pkg_dir / PUBLISHED_FILE).exists()
    with pytest.raises(PublishRefused, match="already published"):
        _publish(pkg_dir, gh, cfg)


