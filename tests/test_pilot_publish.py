NOW = datetime(2026, 10, 15, 12, 0, tzinfo=UTC)


@pytest.fixture
def gh() -> FakeGitHub:
    g = FakeGitHub(login="me")
    g.add_repo("upstream/lib", owner="upstream")
    g.add_issue("upstream/lib", 7)
    g.files[("upstream/lib", "CONTRIBUTING.md")] = "Please run the tests before opening a PR."
    g.modes = {"calc/stats.py": "100644", "run.sh": "100755"}
    return g


def _allowlisted(tmp: Path, reviewed: bool = False) -> PilotConfig:
    entry = RepoEntry(repo="upstream/lib", image="img", test_command="pytest",
                      ai_policy_reviewed=reviewed)  # fmt: skip
    return pilot_config(tmp, allowlist=[entry])


def _approve(pkg_dir: Path, reviewer: str = "Chirag (reviewer)") -> None:
    sha = load_package(pkg_dir).content_sha256()
    approve(pkg_dir, reviewer, confirm=lambda _: sha[:8], show=lambda _: None)


def _publish(
    pkg_dir: Path, gh: FakeGitHub, cfg: PilotConfig, published_this_run: int = 0
) -> PublishResult:
    return publish_package(
        pkg_dir, gh=gh, cfg=cfg, publish=True, now=lambda: NOW, sleep=lambda _: None,
        published_this_run=published_this_run,
    )  # fmt: skip


# --------------------------------------------------------------------------- dry run


def test_dry_run_is_the_default_and_writes_nothing(gh: FakeGitHub, tmp_path: Path) -> None:
    pkg_dir = write(tmp_path)
    cfg = _allowlisted(tmp_path)
    result = publish_package(pkg_dir, gh=gh, cfg=cfg, publish=False, now=lambda: NOW)
    assert result.dry_run
    assert gh.writes == []
    assert not result.would_pass  # not approved yet
    assert {g.name for g in result.gates if not g.ok} == {"approval"}
    assert any("pulls" in c and "draft=true" in c for c in result.planned)
    assert not (pkg_dir / PUBLISHED_FILE).exists()


