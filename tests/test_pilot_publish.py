@pytest.mark.parametrize(
    ("contributing", "reviewed", "ok", "fragment"),
    [
        ("We do not accept pull requests generated by AI tools.", True, False, "prohibits"),
        ("If you used Copilot, please say so in the PR.", False, False, "mentions AI"),
        ("If you used Copilot, please say so in the PR.", True, True, "reviewed"),
        ("Please run the tests first.", False, True, "no AI mention in CONTRIBUTING.md"),
    ],
)
def test_ai_policy_gate(gh: FakeGitHub, tmp_path: Path, *, contributing: str, reviewed: bool,
                        ok: bool, fragment: str) -> None:  # fmt: skip
    gh.files[("upstream/lib", "CONTRIBUTING.md")] = contributing
    result = gate_ai_policy(gh, _allowlisted(tmp_path, reviewed), "upstream/lib")
    assert result.ok is ok
    assert fragment in result.reason


